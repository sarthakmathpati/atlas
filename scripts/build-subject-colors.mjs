#!/usr/bin/env node
// Generates the subject colors (BUILD_SPEC.md 12.10.3) from each subject's hue:
//   content/<subject>/_subject.md  (regionHue: an OKLCH hue)
//     -> src/styles/subjects.generated.css
//
// Every subject shares one lightness and chroma per use, so no subject shouts:
//   Day mark        L 0.53  C 0.11     strokes of emblems, square marks, subject names
//   Day tint        L 0.95  C 0.028    map regions, page-head washes, icon tiles
//   Dusk/Night mark L 0.76  C 0.10
//   Dusk/Night tint L 0.29  C 0.035
// Channels outside sRGB are clipped (this reproduces the spec's table exactly). The CSS defines
// --subject-<id>-mark and --subject-<id>-tint per theme, and [data-subject="<id>"] sets the
// shorthand --subject-mark and --subject-tint for anything drawn for that subject.
//
// The hues are not part of the map layout's structure hash, so recoloring never moves the map.
// `npm run build:colors` (part of build:data) writes the file; a test keeps it up to date.
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { oklchToHex } from "./lib/color.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const CONTENT_DIR = join(ROOT, "content");
const OUT_PATH = join(ROOT, "src", "styles", "subjects.generated.css");

export const SUBJECT_COLOR_LEVELS = {
  dayMark: { L: 0.53, C: 0.11 },
  dayTint: { L: 0.95, C: 0.028 },
  darkMark: { L: 0.76, C: 0.1 },
  darkTint: { L: 0.29, C: 0.035 },
};

/** Reads `{ id, order, hue }` for every subject, in subject order. */
export function readSubjectHues(contentDir = CONTENT_DIR) {
  const subjects = [];
  for (const dir of readdirSync(contentDir, { withFileTypes: true })) {
    if (!dir.isDirectory()) continue;
    const path = join(contentDir, dir.name, "_subject.md");
    if (!existsSync(path)) continue;
    const text = readFileSync(path, "utf8");
    const field = (name) => text.match(new RegExp(`^${name}:\\s*(.+)$`, "m"))?.[1]?.trim();
    const id = field("subject");
    const hue = Number(field("regionHue"));
    const order = Number(field("order"));
    if (!id || !Number.isFinite(hue) || hue < 0 || hue >= 360) {
      throw new Error(`${relative(ROOT, path)}: needs "subject" and a "regionHue" from 0 to 359.`);
    }
    subjects.push({ id, order, hue });
  }
  return subjects.sort((a, b) => a.order - b.order);
}

/** The four colors of each subject, as lowercase hex. */
export function subjectColors(subjects) {
  const at = ({ L, C }, hue) => oklchToHex(L, C, hue);
  return subjects.map(({ id, hue }) => ({
    id,
    hue,
    dayMark: at(SUBJECT_COLOR_LEVELS.dayMark, hue),
    dayTint: at(SUBJECT_COLOR_LEVELS.dayTint, hue),
    darkMark: at(SUBJECT_COLOR_LEVELS.darkMark, hue),
    darkTint: at(SUBJECT_COLOR_LEVELS.darkTint, hue),
  }));
}

export function renderSubjectCss(colors) {
  const vars = (pick) =>
    colors
      .flatMap((c) => [
        `  --subject-${c.id}-mark: ${pick(c).mark};`,
        `  --subject-${c.id}-tint: ${pick(c).tint};`,
      ])
      .join("\n");
  const indent = (text) =>
    text
      .split("\n")
      .map((line) => `  ${line}`)
      .join("\n");
  const helpers = colors
    .map(
      (c) =>
        `[data-subject="${c.id}"] {\n  --subject-mark: var(--subject-${c.id}-mark);\n  --subject-tint: var(--subject-${c.id}-tint);\n}`,
    )
    .join("\n\n");
  return `/*
 * Subject colors (BUILD_SPEC.md 12.10.3). Generated by scripts/build-subject-colors.mjs from the
 * regionHue in content/<subject>/_subject.md. Do not edit by hand: change a hue and run
 * \`npm run build:colors\`.
 * A subject color is a tint (regions, page-head washes, icon tiles), an emblem stroke or a small
 * square mark, never a round dot (round means status) and never without the subject's name.
 */

:root,
[data-theme-preview="day"] {
${vars((c) => ({ mark: c.dayMark, tint: c.dayTint }))}
}

@media not print {
  :root[data-theme="dusk"],
  :root[data-theme="night"],
  [data-theme-preview="dusk"],
  [data-theme-preview="night"] {
${indent(vars((c) => ({ mark: c.darkMark, tint: c.darkTint })))}
  }
}

${helpers}
`;
}

function main() {
  const css = renderSubjectCss(subjectColors(readSubjectHues()));
  const old = existsSync(OUT_PATH) ? readFileSync(OUT_PATH, "utf8") : "";
  if (old === css) {
    console.log(`✓ Subject colors are up to date (${relative(ROOT, OUT_PATH)}).`);
    return;
  }
  writeFileSync(OUT_PATH, css);
  console.log(`✓ Wrote ${relative(ROOT, OUT_PATH)}.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
